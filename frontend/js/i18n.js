let currentLang = localStorage.getItem('mt_lang') || 'pl';

function t(key, replacements) {
    let val = (I18N[currentLang] && I18N[currentLang][key]) || (I18N.en && I18N.en[key]) || key;
    if (replacements) { for (const [k, v] of Object.entries(replacements)) { val = val.replace('{' + k + '}', v); } }
    return val;
}

function applyI18n() {
    document.documentElement.lang = currentLang;
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n'); const val = t(key); if (val) el.innerHTML = val;
    });
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
        const key = el.getAttribute('data-i18n-placeholder'); const val = t(key); if (val) el.placeholder = val;
    });
    document.getElementById('langToggle').textContent = t('langLabel');
    // SEO head per language
    try {
        document.title = t('metaTitle');
        const md = document.querySelector('meta[name="description"]');
        if (md) md.setAttribute('content', t('metaDesc'));
        const ogt = document.querySelector('meta[property="og:title"]');
        if (ogt) ogt.setAttribute('content', t('metaTitle'));
        const ogd = document.querySelector('meta[property="og:description"]');
        if (ogd) ogd.setAttribute('content', t('metaDesc'));
    } catch(e) {}
}

function toggleLang() {
    currentLang = currentLang === 'pl' ? 'en' : 'pl';
    localStorage.setItem('mt_lang', currentLang);
    applyI18n();
    if (document.getElementById('userPanel').style.display !== 'none') {
        const nb = document.getElementById('navLinks');
        const admLink = nb.querySelector('a[href="/admin"]');
        if (admLink) admLink.textContent = 'Admin';
    }
}

